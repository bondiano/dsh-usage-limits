// Bundle src/client.ts (ESM) into dist/client.js. Runs after `tsc`, which
// creates dist/ and compiles the Host half; nothing in dist/ is deleted here.
// xstate and the usage machine are bundled in — the Host module registry does
// not provide them to browser clients — while react stays external and is
// resolved through the `__ModuleLoader__` factory's require at runtime.
// Edit src/client.ts, never the generated dist/client.js.
import { build } from 'esbuild'
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')

const result = await build({
  entryPoints: [join(root, 'src/client.ts')],
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  external: ['react'],
  write: false,
  logLevel: 'silent',
})
const generated = result.outputFiles[0].text.trimEnd()

const client = `/**
 * Client half of \`@local/dsh-usage-limits\` — generated by scripts/build-client.mjs; edit src/client.ts instead.
 *
 * Registers one left-sidebar entry and the main panel it opens. The panel
 * reads the same-origin snapshot served by this package's Host half and draws
 * provider quota windows, balances, the default model's capacity, and the
 * deployment limits other services expose.
 */
window.__ModuleLoader__.load({
  id: '@local/dsh-usage-limits',
  factory(require) {
    var module = { exports: {} };
    var exports = module.exports;
${generated}
    return module.exports.default(require);
  },
})
`

const outputPath = join(root, 'dist/client.js')
writeFileSync(outputPath, client)
console.log(`dist/client.js written (${client.length} bytes) from src/client.ts`)
